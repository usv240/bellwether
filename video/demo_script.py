"""Write BELLWETHER_DEMO_SCRIPT.md at the hackathon root from beats.py.

    python video/demo_script.py

The narration comes from the same beats the recorder reads, so the human
script and the video cannot disagree. Only the "where to point" notes
live here.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from beats import BEATS, CHECKIN_DAYS  # noqa: E402

SITE = "https://d1xfuyog8wiuvf.cloudfront.net"
OUT = HERE.parents[1] / "BELLWETHER_DEMO_SCRIPT.md"

WHERE = {
    "hook": ("Home page, top.",
             "Hold still on the headline for a second, then point at the chart on the right, at the dots that leave the shaded band."),
    "gap": ("Home page.",
            'Point at the "3.5 years" card. On "nearly four in five", scroll to "What people say they want" and point at "79%".'),
    "what": ('Home page, "How it works".',
             "Point at the four steps left to right, Wear, Measure, Learn, Show, and rest on Learn."),
    "term-host": ("Terminal, laptop speaker on, the Bee on your wrist.",
                  "On the evening of the take, run `python video/record_term.py capture --only term-host` and answer each question out loud. "
                  "The shot shows the sequence in order: the question spoken, \"you answer; the Bee on your wrist is recording\", "
                  "\"The Bee recorded the check-in\", the day counted, and the note read back."),
    "checkins": (f"{SITE}/app/?profile=me-voice",
                 'Point at the green badge "Real Bee: check-ins", then at the filled days in the first-week card.'),
    "change": ('Same page. Click the tab "Simulated person".',
               'Point at the "Simulated person" label. Rest on the "Eight weeks" chart and trace the dots as they leave the shaded band. '
               'On "how far", point at the first line ending "lower than your baseline since". On "Poor sleep", scroll to "What else could explain this" and hold.'),
    "proof": ("Same page, the chart back in view.",
              'A note appears top right: the tests, 349 Supreme Court arguments with no alerts, 652 presidential press conferences with 18 flagged, '
              'and "Software behaviour, not medical accuracy". Point at the chart while it reads.'),
    "mcp": ('Home page, "Ask Alexa+ how you have been sounding".',
            'Click "Start a session" and point at the rows as they fill: protocol agreed, nine tools listed, the answer returned.'),
    "term-agent": ("Terminal.",
                   "The Strands agent runs against the deployed server; point at the line where it says the data is simulated."),
    "report": (f"{SITE}/report/",
               'On "simple timeline", point at "Tier over the period". On "what questions to ask", scroll to "For the Annual Wellness Visit" '
               'and point at "Questions to bring". On "Open source", the end card with the links appears.'),
}

PROVES = {
    "hook": "Impact", "gap": "Impact", "what": "Idea", "term-host": "Tech, and the Bee track rule",
    "checkins": "Tech, and the Bee track rule", "change": "Design and Idea", "proof": "Tech and Impact",
    "mcp": "Tech, Alexa+", "term-agent": "Tech, AWS", "report": "Impact and Design",
}


def main() -> int:
    missing = [b.key for b in BEATS if b.key not in WHERE]
    if missing:
        print(f"no pointing notes for {missing}", file=sys.stderr)
        return 1
    rows, body, t = [], [], 0.0
    for i, b in enumerate(BEATS, 1):
        m, s = divmod(int(round(t)), 60)
        rows.append(f"| {i}. {b.key} | {m}:{s:02d} | {PROVES[b.key]} |")
        screen, do = WHERE[b.key]
        body += [f"## {i}. {b.key} ({m}:{s:02d})", "", f"**Screen:** {screen}", f"**Do:** {do}", "", f'**"{b.say}"**', ""]
        t += b.seconds
    m, s = divmod(int(round(t)), 60)
    out = [
        "# Bellwether demo script", "",
        "Generated by `bellwether/video/demo_script.py` from `video/beats.py`, the file the recorder reads, so these are the words in the video. "
        "**Bold is what is said.** \"Screen\" is where you are; \"Do\" is where to point and what to click.", "",
        "One story: you speak to your Bee, Bellwether learns your normal, a change becomes visible, and you have something clear to take to your doctor.", "",
        "## Before the take", "",
        "- Band on your wrist, phone with the Bee app nearby, laptop volume up, quiet room.",
        f"- `CHECKIN_DAYS` in `video/beats.py` is {CHECKIN_DAYS}. Set it to the live day count; the recorder refuses to start if they differ.",
        "- Browser at 100% zoom, notifications off.", "",
        "| Beat | Starts | Proves |", "|---|---|---|", *rows, "",
        f"Estimated end {m}:{s:02d}, against a 3:00 limit.", "",
        *body,
        "## What is never said", "",
        '- "Detects", "diagnoses", "predicts" or "screens for" any condition. "Early detection." Any accuracy figure about Bellwether itself.',
        "- That the simulated person is real, or that Alexa+ itself spoke.",
        "- Any number that is not in docs/EVIDENCE.md.", "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(BEATS)} beats, ends {m}:{s:02d}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
